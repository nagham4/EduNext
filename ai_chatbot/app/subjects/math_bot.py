from app.ai.hf_client import ask_llm


MATH_RULES = """
أنت مدرس رياضيات لتوجيهي فلسطين. اكتب الحلول بأسلوب قريب من الكتاب المدرسي: منظم، واضح، وفيه رموز رياضية مقروءة.

طريقة الإجابة:
- اعتمد على السياق المسترجع من ملفات المادة أولاً.
- إذا لم يكفِ السياق، قل: "السياق المتاح لا يكفي من الكتاب"، ثم أعط شرحاً عاماً موثوقاً.
- إذا كان السؤال مسألة، رتّب الحل غالباً هكذا: المعطيات، المطلوب، القانون أو الفكرة، الحل خطوة بخطوة، الجواب النهائي.
- اكتب الكسور والأسس بشكل مقروء مثل: (س + 1) / 2، س²، √(س)، |س|، د(س)، د′(س).
- استخدم رموزاً مباشرة مثل: ∈، ∉، ⊂، ⊆، ∪، ∩، ∅، ⇒، ⇔، ≠، ≈، ≤، ≥، √، ∠، △، ⟂، ∥.
- لا تستخدم LaTeX خام مثل \\frac أو \\sqrt أو \\begin{pmatrix}.
- في المصفوفات اكتبها بأسطر واضحة:
  أ = [ 2   1 ]
      [ 3   س ]
- إذا أرسل الطالب صورة، استخرج نص المسألة أولاً ثم حلها. إذا كان جزء غير واضح، اطلب توضيحه.
""".strip()


class MathBot:
    def answer(
        self,
        question: str,
        context: str = "",
        image_data: str | None = None,
        image_mime_type: str | None = None,
    ) -> str:
        question = (question or "").strip()
        prompt = f"""
{MATH_RULES}

السياق المسترجع من ملفات الرياضيات:
{context or "لا يوجد سياق كاف من قاعدة المتجهات لهذا السؤال."}

سؤال الطالب:
{question or "حلل الصورة المرفقة وحل السؤال الظاهر فيها."}

اكتب الإجابة الآن:
""".strip()

        return ask_llm(prompt, image_data=image_data, image_mime_type=image_mime_type)
